import assert from 'node:assert/strict';
import {nextTick,defineComponent,h,ref} from 'vue';
import {mount} from './mount-component.mjs';
import MobileSidebar from '../src/components/MobileSidebar.vue';
import {openMobileSidebar,closeMobileSidebar,mobileSidebar,mobileSidebarHeight,readMobileSidebarHeight,MOBILE_SIDEBAR_HEIGHT_KEY} from '../src/ui/mobile-sidebar.js';
const original=window.matchMedia;
let isMobile=true;
window.matchMedia=()=>({matches:isMobile,addEventListener(){},removeEventListener(){}});
const text=ref('First person');
const fixture=defineComponent({setup:()=>()=>h(MobileSidebar,{sidebarKey:'test',label:'Test details'},()=>h('aside',text.value))});
localStorage.removeItem(MOBILE_SIDEBAR_HEIGHT_KEY);mobileSidebarHeight.value=readMobileSidebarHeight();
const card=mount(fixture);
await nextTick();
assert.equal(card.find('.mobile-sidebar-shell').attributes('aria-hidden'),'true');
openMobileSidebar('test');await nextTick();await nextTick();
assert(card.find('.mobile-sidebar-shell').attributes('class').includes('is-open'));
assert(card.find('.mobile-sidebar-shell').attributes('style').includes('40dvh'));
assert.equal(card.findAll('[aria-modal]').length,0,'No modal backdrop or focus trap');
assert.equal(document.body.style.overflow,'','Background scrolling stays enabled');
await card.find('.mobile-sidebar-grip').trigger('keydown',{key:'ArrowUp'});
assert(card.find('.mobile-sidebar-shell').attributes('style').includes('45dvh'));
assert.equal(readMobileSidebarHeight(),45,'Chosen height survives browser storage round trip');
text.value='Second person';openMobileSidebar('test');await nextTick();
assert(card.text().includes('Second person'));
assert(card.find('.mobile-sidebar-shell').attributes('style').includes('45dvh'),'Content swaps retain resized height');
await card.find('.mobile-sidebar-close').trigger('click');
assert.equal(mobileSidebar.value.key,null);
openMobileSidebar('test');await nextTick();
const pointer=(type,y,time)=>{const event=new Event(type,{bubbles:true});Object.defineProperties(event,{clientY:{value:y},timeStamp:{value:time},button:{value:0}});card.find('.mobile-sidebar-grip').element.dispatchEvent(event);};
pointer('pointerdown',100,1000);pointer('pointermove',200,1100);pointer('pointerup',200,1150);await nextTick();
assert.equal(mobileSidebar.value.key,null,'Quick downward swipe dismisses');
assert.equal(mobileSidebarHeight.value,45,'Dismiss swipe retains previous chosen height');
assert.equal(readMobileSidebarHeight(),45);
card.find('.mobile-sidebar-body').element.scrollTop=30;await card.find('.mobile-sidebar-body').trigger('scroll');
assert(card.find('.mobile-sidebar-shell').attributes('class').includes('is-scrolled'));
for(const invalid of ['oops','0','100','']){localStorage.setItem(MOBILE_SIDEBAR_HEIGHT_KEY,invalid);assert.equal(readMobileSidebarHeight(),40);}
localStorage.removeItem(MOBILE_SIDEBAR_HEIGHT_KEY);
closeMobileSidebar();isMobile=false;openMobileSidebar('test');assert.equal(mobileSidebar.value.key,null,'Desktop sidebar stays inline');
card.unmount();window.matchMedia=original;
console.log('Passed: 40%-height cards, resizing, content swaps, close, swipe dismissal, desktop guard and live background.');
