import assert from 'node:assert/strict';
import {nextTick} from 'vue';
import {mount} from './mount-component.mjs';
import TimelinePage from '../src/pages/TimelinePage.vue';
import {showWorldEvents} from '../src/ui/timeline-history.js';
import {bindRuntime,ui} from '../src/ui/runtime.js';
const person={id:'p',name:'Test Person',birthday:'1969-01-01'};
bindRuntime({familyDateYear:d=>Number(d.slice(0,4)),familyDateLabel:d=>d,displayName:p=>p.name,initials:()=> 'TP',upcomingAnniversaries:()=>[],onThisDayEvents:()=>[],milestoneIcons:{},personMatchesQuery:()=>true});
ui.sync({people:[person],links:[],albums:[],milestones:[]});
ui.setTimeline([{kind:'birth',id:'p',person,date:person.birthday}]);showWorldEvents.value=false;
const page=mount(TimelinePage);
assert.equal(page.findAll('.timeline-world-events').length,0,'History starts hidden');
const toggle=page.find('.timeline-history-toggle input');toggle.element.checked=true;await toggle.trigger('change');
assert.equal(localStorage.getItem('kinfolk-timeline-world-events-v1'),'true');
assert.equal(page.findAll('.timeline-world-event').filter(e=>e.text().includes('People land on the Moon')).length,1);
assert.equal(page.findAll('.world-event-category, .world-event-relation').length,0);
assert.equal(page.findAll('.birth-event').length,1,'Family entries remain unchanged');
assert.equal(page.findAll('.timeline-world-event > p:not(.world-event-relation)').length,0,'Descriptions are omitted');
assert.equal(page.findAll('.timeline-world-event a').length,page.findAll('.timeline-world-event').length,'Only the event title links to its source');
const link=page.find('.timeline-world-event a');assert.match(link.attributes('href'),/^https:/);assert.equal(link.attributes('rel'),'noopener noreferrer');
assert(page.find('.timeline-world-event time').attributes('datetime'));
assert.equal(page.findAll('.timeline-world-event h4').length,0,'Title stays inline with date and country');
await toggle.trigger('change');
toggle.element.checked=false;await toggle.trigger('change');
assert.equal(page.findAll('.timeline-world-events').length,0);assert.equal(localStorage.getItem('kinfolk-timeline-world-events-v1'),'false');
page.unmount();showWorldEvents.value=true;await nextTick();const restored=mount(TimelinePage);assert(restored.find('.timeline-history-toggle input').element.checked);restored.unmount();
ui.setTimeline([{kind:'birth',id:'p',person,date:'1835'}]);
const early=mount(TimelinePage);assert(early.find('.timeline-world-events').text().includes('Manila formally opens to world trade'));assert(early.findAll('.timeline-world-event time').some(time=>time.text()==='1834'),'Year-only historical dates never invent a month or day');early.unmount();showWorldEvents.value=false;
console.log('Passed: toggle, local preference persistence, contextual notes, safe source links, preserved family entries and hiding history.');
